// Абстрактный класс Shape - нельзя создать объект этого класса напрямую
// abstract - ключевое слово, указывающее что класс абстрактный
// Абстрактный класс служит шаблоном для других классов
abstract class Shape {
    // Абстрактный метод draw() - не имеет реализации (тела)
    // public - доступен везде
    // abstract - метод без реализации, должен быть реализован в подклассах
    // void - не возвращает значение
    // draw() - название метода
    // Обратите внимание: после сигнатуры метода стоит ТОЛЬКО точка с запятой!
    public abstract void draw();
    // Абстрактные методы ЗАСТАВЛЯЮТ подклассы предоставить свою реализацию
}

// Подкласс Circle - наследует от абстрактного класса Shape
// class Circle extends Shape - Circle является конкретной реализацией Shape
class Circle extends Shape {
    // @Override - аннотация указывает что метод переопределяет абстрактный метод родителя
    @Override
    // Реализация абстрактного метода draw() для круга
    // public void draw() - должна точно совпадать с сигнатурой абстрактного метода
    public void draw() {
        // Конкретная реализация метода для круга
        // System.out.println() - вывод в консоль
        // "Рисуется круг" - сообщение о том, что рисуется круг
        System.out.println("Рисуется круг");
    }
    // Теперь Circle является КОНКРЕТНЫМ классом и можно создавать его объекты
}

// Подкласс Rectangle - также наследует от абстрактного класса Shape
// class Rectangle extends Shape - Rectangle является конкретной реализацией Shape
class Rectangle extends Shape {
    // @Override - указывает на переопределение абстрактного метода
    @Override
    // Реализация абстрактного метода draw() для прямоугольника
    public void draw() {
        // Конкретная реализация метода для прямоугольника
        // System.out.println() - вывод в консоль
        // "Рисуется прямоугольник" - сообщение о том, что рисуется прямоугольник
        System.out.println("Рисуется прямоугольник");
    }
    // Rectangle теперь тоже КОНКРЕТНЫЙ класс
}